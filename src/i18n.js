export function getLocaleData(locale) {
  const language = supportedLocales.includes(locale) ? locale : 'zh';
  const index = language === 'en' ? 1 : 0;
  return {
    ui: Object.fromEntries(Object.entries(uiPairs).map(([key, pair]) => [key, pair[index]])),
    lessons: language === 'en' ? lessonsEn : lessons,
    sourceReference: language === 'en' ? sourceReferenceEn : sourceReference
  };
}

export function interpolate(message, values = {}) {
  return message.replace(/\{(\w+)\}/g, (match, key) => values[key] === undefined ? match : String(values[key]));
}

export function resolveLocale(storage, search = '') {
  const requested = new URLSearchParams(search).get('lang');
  if (supportedLocales.includes(requested)) return requested;
  try {
    const saved = storage.getItem(LOCALE_KEY);
    if (supportedLocales.includes(saved)) return saved;
  } catch { /* Storage restrictions must not block language selection. */ }
  return 'zh';
}

export function saveLocale(storage, locale) {
  if (!supportedLocales.includes(locale)) return false;
  try { storage.setItem(LOCALE_KEY, locale); return true; } catch { return false; }
}
